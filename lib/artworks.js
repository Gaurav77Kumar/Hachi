// Derives a deterministic two-color gradient from the artwork title so each
// card feels distinct even before its image loads.
function artGradient(title) {
  let h = 0;
  for (let i = 0; i < title.length; i++) h = (h * 31 + title.charCodeAt(i)) >>> 0;
  const h1 = h % 360;
  const h2 = (h1 + 40 + (h % 80)) % 360;
  return `linear-gradient(150deg, hsl(${h1} 45% 22%), hsl(${h2} 50% 12%))`;
}

function artImageUrl(file, width = 800) {
  return `https://commons.wikimedia.org/wiki/Special:FilePath/${encodeURIComponent(file)}?width=${width}`;
}

